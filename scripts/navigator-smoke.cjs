'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { _electron: electron } = require('playwright');
const { Store } = require('../src/store');

(async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'xiaoxiao-navigator-'));
  let app;
  try {
    const store = new Store(dir);
    const titles = ['产品上线复核', '客户访谈 · 第二轮', '季度经营简报', '设计系统更新', '采购需求汇总', '渠道周会'];
    store.write('projects', [{ id:'project', name:'产品与交付', sources:[] }]);
    store.write('providers', [{ id:'local', kind:'ollama', name:'测试模型', model:'fixture', baseUrl:'http://127.0.0.1:1/v1' }]);
    store.write('conversations', Array.from({ length:44 }, (_, i) => {
      const messages = [{role:'user',content:'整理本周的建议。'}, {role:'assistant',content:'材料已收齐，可以开始复核。'}];
      if (i === 1) messages.push({role:'user',content:'交付清单需要附上负责人。'}, {role:'assistant',content:'已记录。'}, {role:'user',content:'最终交付清单见附件。'});
      if (i === 2) messages.push({role:'assistant',content:'上次运行已中断。',failed:true,recovery:{originalUserIndex:0,tools:[]}});
      return { id:'session-'+i, title:titles[i] || '工作记录 ' + i, agent:i%2===0, pinned:i<2, projectId:i<5?'project':'', providerId:'local', updatedAt:Date.now()-i*86400000, messages };
    }));
    const executablePath = process.env.XIAOXIAO_SMOKE_EXECUTABLE;
    app = await electron.launch({executablePath, args:executablePath ? [] : ['.'], cwd:path.resolve(__dirname,'..'), env:{...process.env,XIAOXIAO_SMOKE_DIR:dir}});
    const page = await app.firstWindow();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const el = id => page.locator('#'+id);
    const shortcut = () => page.keyboard.press('ControlOrMeta+k');
    const focus = id => page.waitForFunction(id => document.activeElement.id === id,id);
    const capture = async name => {
      const out = process.env.XIAOXIAO_SMOKE_QA_DIR;
      if (!out) return;
      await fs.mkdir(out,{recursive:true});
      await page.locator('#searchDialog').screenshot({path:path.join(out,name+'.png'),scale:'css'});
    };
    await page.locator('#presenceKnot:enabled').waitFor();
    await el('presenceKnot').focus();
    await shortcut();
    await focus('historyQuery');
    await el('historyQuery').press('Escape');
    await focus('presenceKnot');
    assert(await el('presence').isVisible());
    await shortcut();
    assert.equal(await page.locator('#historyResults button').count(),40);
    await el('historyMore').click();
    assert.equal(await page.locator('#historyResults button').count(),44);
    await page.locator('[data-scope=pinned]').click();
    assert.equal(await page.locator('#historyResults button').count(),2);
    await page.locator('[data-scope=running]').click();
    await el('historyEmptyTitle').getByText('目前没有运行中的任务').waitFor();
    await el('historyReset').click();
    await el('historyQuery').fill('交付清单');
    assert.equal(await page.locator('#historyResults mark').textContent(),'交付清单');
    await el('historyQuery').press('ArrowDown');
    await page.keyboard.press('Enter');
    await page.waitForFunction(()=>document.activeElement.dataset.messageIndex==='4');
    assert.match(await el('conversationTitle').textContent(),/第二轮/);
    await el('prompt').fill('保留中的草稿');
    await shortcut();
    await page.locator('[data-scope=attention]').click();
    assert.equal(await page.locator('#historyResults button').count(),1);
    await page.locator('#historyResults button').click();
    await focus('resumeTask');
    await shortcut();
    await el('historyQuery').fill('客户访谈');
    await el('historyQuery').press('Enter');
    assert.equal(await el('prompt').inputValue(),'保留中的草稿');
    await shortcut();
    await el('historyQuery').fill('产品与交付');
    assert.equal(await page.locator('#historyResults button').count(),5);
    await el('historyQuery').fill('');
    await el('historyQuery').press('ArrowDown');
    await capture('navigator-dark');
    await el('historyQuery').press('Escape');
    await page.emulateMedia({colorScheme:'light'});
    await el('returnPresence').click();
    await shortcut();
    await page.locator('[data-scope=pinned]').click();
    await capture('navigator-light');
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(900,620));
    await page.waitForFunction(()=>{const e=document.querySelector('#searchDialog');return e.clientWidth>0 && e.scrollWidth<=e.clientWidth && e.scrollHeight<=e.clientHeight+1;});
    assert.deepEqual(errors,[]);
    console.log('PASS: Navigator filters, paging, project and message search, message focus, home dismissal, recoverable task focus, and draft retention.');
  } finally {
    await app?.close();
    await fs.rm(dir,{recursive:true,force:true});
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
